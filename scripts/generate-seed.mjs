// Generates supabase/seed.sql from src/data/content.json (the same file the demo mode uses).
// Usage: node scripts/generate-seed.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const content = JSON.parse(readFileSync(resolve(root, 'src/data/content.json'), 'utf8'));

const uid = (key) => {
  const h = createHash('md5').update('vtiara:' + key).digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
};
const s = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => `array[${a.map(s).join(',')}]::text[]`;
const j = (o) => `'${JSON.stringify(o).replace(/'/g, "''")}'::jsonb`;
const n = (v) => (v === null || v === undefined ? 'null' : Number(v));

const out = [];
out.push('-- GENERATED by scripts/generate-seed.mjs from src/data/content.json — do not edit by hand.');
out.push('-- Safe to re-run: every insert uses fixed IDs with ON CONFLICT DO NOTHING.\n');

out.push('-- branches');
for (const b of content.branches)
  out.push(`insert into public.branches (id, name, city, address, maps_url, phone, hours) values (${s(uid('branch:' + b.key))}, ${s(b.name)}, ${s(b.city)}, ${s(b.address)}, ${s(b.maps_url)}, ${s(b.phone)}, ${s(b.hours)}) on conflict (id) do nothing;`);

for (const c of content.courses) {
  const cid = uid('course:' + c.slug);
  out.push(`\n-- course: ${c.title}`);
  out.push(`insert into public.courses (id, slug, title, code, category, role_key, role_label, status, sort_order, duration_hours, duration_label, level,
  languages, learning_modes, certificate_title, certificate_validity_months, requires_attendance, requires_practical, requires_trainer_approval,
  short_description, overview, audience, eligibility, learning_outcomes, requirements_text, pass_rules) values (
  ${s(cid)}, ${s(c.slug)}, ${s(c.title)}, ${s(c.code)}, ${s(c.category)}, ${s(c.role_key)}, ${s(c.role_label)}, ${s(c.status)}, ${n(c.sort_order)}, ${n(c.duration_hours)}, ${s(c.duration_label)}, ${s(c.level)},
  ${arr(c.languages)}, ${arr(c.learning_modes)}, ${s(c.certificate_title)}, ${n(c.validity_months)}, ${c.requires_attendance}, ${c.requires_practical}, ${c.requires_trainer_approval},
  ${s(c.short_description)}, ${s(c.overview)}, ${s(c.audience)}, ${arr(c.eligibility)}, ${arr(c.outcomes)}, ${arr(c.requirements_text)}, ${j(c.pass_rules)}) on conflict (id) do nothing;`);

  c.modules.forEach((m, mi) => {
    const mid = uid(`module:${c.slug}:${mi}`);
    out.push(`insert into public.course_modules (id, course_id, title, position) values (${s(mid)}, ${s(cid)}, ${s(m.title)}, ${mi + 1}) on conflict (id) do nothing;`);
    m.lessons.forEach((l, li) => {
      const lid = uid(`lesson:${c.slug}:${mi}:${li}`);
      const tr = l.transcript || `Transcript for "${l.title}" will appear here once the recorded class is uploaded.`;
      out.push(`insert into public.lessons (id, module_id, course_id, title, description, duration_min, transcript, position) values (${s(lid)}, ${s(mid)}, ${s(cid)}, ${s(l.title)}, ${s(l.description)}, ${n(l.minutes)}, ${s(tr)}, ${li + 1}) on conflict (id) do nothing;`);
    });
  });

  if (c.assessment) {
    const a = c.assessment;
    const aid = uid('assessment:' + c.slug);
    out.push(`insert into public.assessments (id, course_id, title, time_limit_min, pass_mark, num_questions, retake_after_days, compulsory_category) values (${s(aid)}, ${s(cid)}, ${s(a.title)}, ${n(a.time_limit_min)}, ${n(a.pass_mark)}, ${n(a.num_questions)}, ${n(a.retake_after_days)}, ${s(a.compulsory_category)}) on conflict (id) do nothing;`);
    a.questions.forEach((q, qi) => {
      const qid = uid(`question:${c.slug}:${qi}`);
      out.push(`insert into public.assessment_questions (id, assessment_id, category, prompt, explanation, position) values (${s(qid)}, ${s(aid)}, ${s(q.cat)}, ${s(q.q)}, ${s(q.e)}, ${qi + 1}) on conflict (id) do nothing;`);
      q.o.forEach((label, oi) =>
        out.push(`insert into public.assessment_options (id, question_id, label, is_correct, position) values (${s(uid(`option:${c.slug}:${qi}:${oi}`))}, ${s(qid)}, ${s(label)}, ${oi === q.c}, ${oi + 1}) on conflict (id) do nothing;`));
    });
  }

  if (c.checklist) {
    const k = c.checklist;
    const kid = uid('checklist:' + c.slug);
    out.push(`insert into public.practical_checklists (id, course_id, title, description, requires_evidence, min_score_pct) values (${s(kid)}, ${s(cid)}, ${s(k.title)}, ${s(k.description)}, ${k.requires_evidence}, ${n(k.min_score)}) on conflict (id) do nothing;`);
    k.items.forEach((it, ii) =>
      out.push(`insert into public.practical_checklist_items (id, checklist_id, label, is_critical, position) values (${s(uid(`item:${c.slug}:${ii}`))}, ${s(kid)}, ${s(it.label)}, ${it.critical}, ${ii + 1}) on conflict (id) do nothing;`));
  }
}

out.push('\n-- demo batches (dates are relative to the day you run this seed; trainer is assigned by scripts/seed-users.mjs)');
content.batches.forEach((b, i) => {
  out.push(`insert into public.batches (id, course_id, branch_id, title, starts_on, start_time, end_time, capacity, mode, location, practical_requirements) values (
  ${s(uid('batch:' + i))}, ${s(uid('course:' + b.course))}, ${s(uid('branch:' + b.branch))}, ${s(b.title)}, current_date + ${b.offset_days}, ${s(b.start)}, ${s(b.end)}, ${b.capacity}, ${s(b.mode)},
  (select name || ' — ' || coalesce(address,'') from public.branches where id = ${s(uid('branch:' + b.branch))}),
  'Bring your own uniform. Practical stations are assessed in person by the trainer.') on conflict (id) do nothing;`);
});

mkdirSync(resolve(root, 'supabase'), { recursive: true });
out.push(`\n-- role-specific courses require Common Core (same rule as migration 0007; edit prerequisite_course_id per course to change)
update public.courses c set prerequisite_course_id = cc.id from public.courses cc
where cc.slug = 'common-core' and c.slug <> 'common-core' and c.role_key is not null and c.role_key <> 'all' and c.prerequisite_course_id is null;`);
writeFileSync(resolve(root, 'supabase/seed.sql'), out.join('\n') + '\n');
console.log(`Wrote supabase/seed.sql (${out.length} statements)`);
